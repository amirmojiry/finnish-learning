'use strict';

const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const course = require('../course.js');

const selected = new Set([
  'section-2-lesson-7',
  'section-3-lesson-10',
  'section-3-lesson-5',
  'section-2-lesson-10',
  'a1.2-section-2-lesson-7',
  'a1.3-section-4-lesson-10',
  'section-3-lesson-9',
  'section-4-lesson-9',
]);
function report() {
  const rows = [];
  for (const stage of course.COURSE_STAGES) {
    for (const url of stage.sectionUrls) {
      const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '..', url), 'utf8'));
      const section = course.validateSection(raw);
      for (const lesson of section.lessons) {
        const slides = course.compactLessonActivities(lesson.activities);
        const graded = slides.reduce((sum, slide) => sum + course.scoredOpportunitiesOnSlide(slide), 0);
        const sittings = course.planPacedLessonSessions(slides, lesson.study_pacing);
        // Worst case includes every originally missed graded question as a separate
        // retry slide; a rendered-screen cap alone is insufficient for this phase.
        const allWrongRetries = lesson.activities.filter(
          (activity) => course.scoredOpportunitiesOnSlide(activity) > 0
        );
        const worstCase = course.planPacedLessonFlow(
          slides, allWrongRetries, lesson.study_pacing
        );
        const activityKinds = {};
        for (const activity of lesson.activities) {
          const kind = activity.type + (activity.mode ? ':' + activity.mode : '');
          activityKinds[kind] = (activityKinds[kind] || 0) + 1;
        }
        const productive = lesson.activities.filter(course.isProductiveCourseActivity).length;
        const listening = lesson.activities.filter((activity) => (
          activity.type === 'dictation' || activity.mode === 'listen'
        )).length;
        const morphology = lesson.activities.filter((activity) => (
          ['morphology-choice', 'inflection-production'].includes(activity.type)
        )).length;
        const teaching = lesson.activities.filter((activity) => activity.type === 'teach').length;
        const distinctGradedTargets = new Set(
          lesson.activities.map(course.activityPrimaryTargetId).filter(Boolean)
        ).size;
        rows.push({
          section: section.id,
          lesson: lesson.id,
          authored: lesson.activities.length,
          screens: slides.length,
          graded,
          teaching,
          productive,
          listening,
          morphology,
          distinct_graded_targets: distinctGradedTargets,
          activity_kinds: activityKinds,
          checkpoint_targets: lesson.checkpoint_targets?.length || 0,
          sittings: sittings.length || 1,
          worst_sitting_screens: Math.max(...(sittings.length ? sittings.map(s => s.screens) : [slides.length])),
          worst_sitting_answers: Math.max(...(sittings.length ? sittings.map(s => s.graded) : [graded])),
          sitting_details: sittings,
          all_wrong_retry_sittings: Math.max(0, worstCase.length - sittings.length),
          all_wrong_sittings_total: worstCase.length || 1,
          all_wrong_max_screens: Math.max(...(worstCase.length ? worstCase.map(x => x.screens) : [slides.length])),
          all_wrong_max_answers: Math.max(...(worstCase.length ? worstCase.map(x => x.graded) : [graded])),
          all_wrong_sitting_details: worstCase,
          paced: Boolean(lesson.study_pacing),
        });
      }
    }
  }
  return rows;
}
function markdown(rows) {
  const focus = rows.filter((row) => selected.has(row.lesson));
  const lines = [
    '# Course practice-load and pacing QA',
    '',
    'Generated by `npm run lesson:load:report`. Counts are static authored opportunities, not measured time, fatigue or user abandonment.',
    '',
    '| Lesson | Original activities | Initial screens | Graded answers total | Study sittings | Max screens / sitting | Max graded answers / sitting |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
  ];
  focus.forEach(row => lines.push(
    `| ${row.section}/${row.lesson} | ${row.authored} | ${row.screens} | ${row.graded} | ${row.sittings} | ${row.worst_sitting_screens} | ${row.worst_sitting_answers} |`
  ));
  lines.push(
    '',
    '| Lesson | Teaching cards | Productive answers | Listening/dictation | Morphology | Distinct target IDs | Activity families |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: |'
  );
  focus.forEach((row) => lines.push(
    `| ${row.section}/${row.lesson} | ${row.teaching} | ${row.productive} | ${row.listening} | ${row.morphology} | ${row.distinct_graded_targets} | ${Object.keys(row.activity_kinds).length} |`
  ));
  lines.push(
    '',
    '| Lesson | Initial sittings | Additional retry sittings if all wrong | Worst-case total sittings | Maximum screens per sitting | Maximum answers per sitting |',
    '| --- | ---: | ---: | ---: | ---: | ---: |'
  );
  focus.forEach((row) => lines.push(
    `| ${row.section}/${row.lesson} | ${row.sittings} | ${row.all_wrong_retry_sittings} | ${row.all_wrong_sittings_total} | ${row.all_wrong_max_screens} | ${row.all_wrong_max_answers} |`
  ));
  lines.push('', 'Pacing divides each learner-effective lesson edition into multiple *optional sittings* with safe local resume, and bounds retry sittings separately. Editorial revisions can reduce total graded work; pacing alone does not reduce it or certify CEFR/YKI. In a later editorial migration, genuine lesson splitting and activity reduction require independent mastery and progress analysis.', '');
  return lines.join('\n');
}
function check(rows) {
  assert.equal(rows.length, 140);
  const paced = rows.filter(r => r.paced);
  assert.equal(paced.length, 8);
  assert.deepEqual(new Set(paced.map(r => r.lesson)), selected);
  for(const r of paced) {
    assert.ok(r.sittings >= 2);
    assert.ok(r.worst_sitting_screens <= 15 && r.worst_sitting_answers <= 20);
    assert.equal(r.sitting_details[0].start,0);
    assert.equal(r.sitting_details.at(-1).end,r.screens);
    assert.equal(r.sitting_details.reduce((n,s)=>n+s.graded,0),r.graded);
    assert.ok(r.productive > 0 && r.listening > 0 && r.distinct_graded_targets > 0);
    assert.ok(Object.keys(r.activity_kinds).length >= 4);
    assert.ok(r.all_wrong_retry_sittings > 0);
    assert.ok(r.all_wrong_max_screens <= 15 && r.all_wrong_max_answers <= 20);
    assert.equal(r.all_wrong_sitting_details.at(-1).end, r.screens + r.graded);
    for (let index = 1; index < r.all_wrong_sitting_details.length; index++) {
      assert.equal(r.all_wrong_sitting_details[index - 1].end,
        r.all_wrong_sitting_details[index].start);
    }
  }
  assert.equal(rows.filter(r=>r.screens>30).length,0);
  console.log('Practice load: all eight paced lessons have bounded sittings; 140 lesson slides remain valid.');
}
const mode = process.argv[2] || '--check';
const rows = report();
if (mode === '--check') check(rows);
else if (mode === '--markdown') process.stdout.write(markdown(rows));
else if (mode === '--json') process.stdout.write(JSON.stringify(rows,null,2)+'\n');
else throw new Error('Usage: --check|--markdown|--json');

module.exports = { report, check, markdown };
